"""Where every file lives. Nothing else builds a data path: a builder, a tool or a test names a file here.

Data is not code, so it is not in the repository. Three places:
  CONFIG  config/  the curated inputs a person maintains (the product catalog, the taxonomy, vocabulary, thresholds): small, in git.
  DATA    data/    working data: saved responses, intermediate files and the databases. Not in git. AIRSTACK_DATA (read once, before the
                   first import) moves it, so a copy of the data can be read or rebuilt from anywhere.
  SITE    data/site/  the published datasets generated by the builders and served by the site. Not in git:
                   production serves them and tools/data_pull.sh downloads them.
The rendered page folders (p/, o/, c/, t/, compare/) are build output in the repository root, ignored by git."""
