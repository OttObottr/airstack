def read_js(path):
    """The JSON object inside a generated `window.X = {...};` wrapper (site-data.js, market-data.js)."""
    text = Path(path).read_text()
    return json.loads(text[text.index("{"):text.rindex("}") + 1])


def config(name):
    """A curated vocabulary or threshold file from config/ (one small JSON file per reader; each names its reader in `_read_by`)."""
    return json.loads((CONFIG / f"{name}.json").read_text())
